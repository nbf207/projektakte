@guarded
@transaction.atomic
def save_entry(owner, project, cleaned, token, entry=None, expected_version=None):
    check_owner(owner,project)
    if DiscardedDraft.objects.filter(owner=owner,token=token).exists():
        raise Conflict('Dieser Entwurf wurde gelöscht. Bitte einen neuen Eintrag öffnen.')
    cleaned=cleaned.copy()
    before=Entry.objects.get(pk=entry.pk) if entry else None
    prior=Entry.objects.filter(request_key=token).first()
    if not entry and prior:
        check_owner(owner,prior)
        return prior
    if entry:
        entry=Entry.objects.get(pk=entry.pk)
        check_owner(owner,entry)
        if entry.version!=expected_version: raise Conflict('Zwischenzeitliche Änderung erkannt. Dein Entwurf bleibt erhalten. Vergleiche die aktuelle Fassung und öffne die Bearbeitung erneut.')
        from .invoice_chronicle import retain_entry_inferences
        retain_entry_inferences(entry,cleaned)
        entry.version+=1
    else: entry=Entry(project=project,request_key=token)
    change_costs='manual_amount' in cleaned
    amount=cleaned.pop('manual_amount',None)
    definition=cleaned.pop('_definition',None)
    for field,value in cleaned.items(): setattr(entry,field,value)
    if before is not None and (entry.date!=before.date or entry.precision!=before.precision):
        entry.snapshot={k:v for k,v in entry.snapshot.items() if k!='_date_source'}
    if 'category' in cleaned:
        if entry.category_id: check_owner(owner,entry.category)
        entry.snapshot={**entry.snapshot,'_category_selected':True}
    elif entry._state.adding:
        from .categories import default_category
        entry.category=default_category(project,entry.kind)
    from .definitions import apply_definition,sync_classification
    if definition is not None:apply_definition(entry,definition,manual=True)
    sync_classification(entry)
    entry.full_clean(exclude=['request_key'])
    entry.save()
    from .entry_links import sync_after_edit
    sync_after_edit(entry,before)
    from .template_maintenance import sync_entry
    sync_entry(entry,before)
    from .i18n import effective_currency
    curr=effective_currency(owner)
    existing=entry.allocations.filter(source__document__isnull=True,source__currency=curr).select_related('source').first()
    if change_costs and amount is not None:
        if existing:
            # Only edit the one-entry manual expense generated by this form.
            source=existing.source
            if source.allocations.count()!=1: raise ValidationError('Geteilte Ausgabe bitte unter Kosten bearbeiten.')
            source.amount=amount;source.version+=1;source.save(update_fields=['amount','version'])
            existing.amount=amount;existing.save(update_fields=['amount'])
        elif not entry.allocations.exists():
            source=CostSource.objects.create(owner=owner,label=entry.title,amount=amount,currency=curr)
            Allocation.objects.create(source=source,project=project,entry=entry,amount=amount)
        elif entry.cost!=amount:
            raise ValidationError('Die vorhandenen Belegkosten bitte über die Kostenquelle korrigieren.')
    elif change_costs and existing:
        existing.source.delete()
    audit(owner,entry,'Gespeichert',{'title':entry.title,'snapshot':entry.snapshot,'date':str(entry.date),'precision':entry.precision,'cost_state':entry.cost_state,'meter':str(entry.meter) if entry.meter is not None else None,'costs':[{'source':str(a.source_id),'amount':str(a.amount),'currency':a.source.currency} for a in entry.allocations.select_related('source')]})
    Draft.objects.filter(owner=owner,token=token).delete()
    return entry



@guarded
@transaction.atomic
def change_deleted(owner,entry,version,restore=False):
    entry=Entry.objects.get(pk=entry.pk);check_owner(owner,entry)
    if entry.version!=version: raise Conflict('Zwischenzeitliche Änderung. Seite neu laden.')
    entry.deleted_at=None if restore else timezone.now();entry.version+=1;entry.save()
    from .template_maintenance import sync_entry
    sync_entry(entry)
    audit(owner,entry,'Wiederhergestellt' if restore else 'Papierkorb',{'title':entry.title})

@guarded
@transaction.atomic
def confirm_import(owner,batch):
    batch=ImportBatch.objects.get(pk=batch.pk);check_owner(owner,batch)
    if batch.confirmed: return
    for i,row in enumerate(batch.rows):
        dt,precision=parse_date(row.get('date'))
        token=uuid.uuid5(batch.pk,str(i))
        save_entry(owner,batch.project,{'title':row['title'],'kind':row.get('kind','wartung'),'date':dt,'precision':precision,'snapshot':{**(row.get('snapshot') or {}),'source':batch.source_name,'source_hash':batch.sha256,'source_row':i+1,'source_page':row.get('source_page'),'source_asset':str(batch.source_asset_id) if batch.source_asset_id else None},'description':row.get('description',''),'meter':decimal_input(row.get('km')),'cost_state':row.get('cost_state') or ('known' if row.get('cost') else 'unknown'),'manual_amount':decimal_input(row.get('cost'),money=True)},token)
    batch.confirmed=True;batch.save()
